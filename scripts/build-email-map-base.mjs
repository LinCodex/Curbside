// NYC DCP Borough Boundaries; a bundled overview avoids billable map-image requests.
import fs from "node:fs/promises";
import sharp from "sharp";
import { deflateSync } from "node:zlib";
const source = "https://data.cityofnewyork.us/resource/gthc-hcne.geojson";
const data = await (await fetch(source)).json();
const bounds = [-74.27, 40.48, -73.7, 40.92];
const width = 640,
  height = 420,
  pad = 24;
const mercator = (lat) =>
  Math.log(Math.tan(Math.PI / 4 + (lat * Math.PI) / 360));
const project = ([lng, lat]) => [
  pad + ((lng - bounds[0]) / (bounds[2] - bounds[0])) * (width - 2 * pad),
  height -
    pad -
    ((mercator(lat) - mercator(bounds[1])) /
      (mercator(bounds[3]) - mercator(bounds[1]))) *
      (height - 2 * pad),
];
const paths = data.features
  .map((feature) =>
    feature.geometry.coordinates
      .map((polygon) =>
        polygon
          .map(
            (ring) =>
              "M" +
              ring
                .map((point) =>
                  project(point)
                    .map((n) => n.toFixed(1))
                    .join(","),
                )
                .join("L") +
              "Z",
          )
          .join(""),
      )
      .join(""),
  )
  .join("");
const labels = [
  ["MANHATTAN", -73.985, 40.8],
  ["BRONX", -73.86, 40.875],
  ["QUEENS", -73.79, 40.75],
  ["BROOKLYN", -73.93, 40.62],
  ["STATEN ISLAND", -74.15, 40.57],
];
const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}"><rect width="100%" height="100%" fill="#101820"/><path d="${paths}" fill="#283c45" stroke="#5a727c" stroke-width=".8" fill-rule="evenodd"/>${labels
  .map(([name, lng, lat]) => {
    const [x, y] = project([lng, lat]);
    return `<text x="${x}" y="${y}" fill="#b7c6cd" font-family="sans-serif" font-size="10" text-anchor="middle" letter-spacing="1">${name}</text>`;
  })
  .join(
    "",
  )}<text x="24" y="20" fill="#b7c6cd" font-family="sans-serif" font-size="11">NYC · LOCATION OVERVIEW</text><text x="24" y="408" fill="#8da1ab" font-family="sans-serif" font-size="10">NYC DCP Borough Boundaries · Positions may be approximate</text></svg>`;
const raw = await sharp(Buffer.from(svg)).ensureAlpha().raw().toBuffer();
await fs.writeFile(
  "lib/email-map-base.ts",
  `// Generated by scripts/build-email-map-base.mjs from NYC DCP Borough Boundaries.\nexport const EMAIL_MAP_BASE = ${JSON.stringify(deflateSync(raw).toString("base64"))};\nexport const EMAIL_MAP_BOUNDS = ${JSON.stringify(bounds)};\n`,
);
